def _stems(text: str) -> set[str]:
    normalized = text.lower().replace("ё", "е")
    return {t[:_STEM_LEN] for t in _TOKEN_RE.findall(normalized) if len(t) >= 3}


_TITLE_WEIGHT = 2.0
_KEYWORD_WEIGHT = 1.5
_TEXT_WEIGHT = 0.5


def score(query: str, instruction: Instruction) -> float:
    """Оценить релевантность инструкции запросу. Заменяет косинусную близость эмбеддингов."""
    query_stems = _stems(query)
    if not query_stems:
        return 0.0
    title_stems = _stems(instruction.title)
    keyword_stems = _stems(" ".join(instruction.keywords))
    text_stems = _stems(instruction.text)

    total = 0.0
    for stem in query_stems:
        if stem in title_stems:
            total += _TITLE_WEIGHT
        elif stem in keyword_stems:
            total += _KEYWORD_WEIGHT
        elif stem in text_stems:
            total += _TEXT_WEIGHT
    return total / len(query_stems)


def rank(query: str, limit: int) -> list[tuple[Instruction, float]]:
    """Инструкции по убыванию релевантности, только с ненулевым скором."""
    scored = ((instr, score(query, instr)) for instr in INSTRUCTIONS.values())
    ranked = sorted(
        (pair for pair in scored if pair[1] > 0),
        key=lambda pair: (-pair[1], pair[0].id),
    )
    return ranked[:limit]
